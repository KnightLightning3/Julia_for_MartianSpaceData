# 重复分块与同时调用：捕捉工作区被闭包共享的竞态；只读系数，输出分别独占。
function check_batch_isolation()
    for n in (0, 1, 255, 256, 257, 513, 2000, 5000)
        rs, θs, ϕs = random_points(n; seed=n + 17)
        ref = Vector{NTuple{4,Float64}}(undef, n)
        serial_loop!(M.IGRF!, M.IGRFWorkspace(), ref, rs, θs, ϕs)
        for mc in (1, 256, n + 1)
            outputs = [similar(ref) for _ in 1:4]
            @sync for out in outputs
                Threads.@spawn begin
                    for _ in 1:3
                        @assert M.IGRF_batch!(out, rs, θs, ϕs; min_chunk=mc) === out
                        @assert isequal(out, ref) "工作区隔离失败：n=$n, min_chunk=$mc"
                    end
                end
            end
        end
    end
    println("分块边界、重复调用、同时批量调用均逐位一致 ✓")
end
check_batch_isolation()

