# ---------------------------------------------------------------- 工具函数
"""
    random_points(n; seed, r_range, θ_range, dyadic_ϕ=false) -> (rs, θs, ϕs)

在给定范围内生成 n 个随机球坐标点（θ 默认避开极点）。
"""
function random_points(n; seed=2024, r_range=(3400.0, 6000.0), θ_range=(0.05, π - 0.05), dyadic_ϕ=false)
    rng = MersenneTwister(seed)
    rs = [r_range[1] + (r_range[2] - r_range[1]) * rand(rng) for _ in 1:n]
    θs = [θ_range[1] + (θ_range[2] - θ_range[1]) * rand(rng) for _ in 1:n]
    ϕs = [-π + 2π * rand(rng) for _ in 1:n]
    dyadic_ϕ && (ϕs = round.(ϕs .* 1024) ./ 1024)
    return rs, θs, ϕs
end

"黄金场值回归：最大分量误差 / 该点总场强 |B|"
function golden_err_B(rs, θs, ϕs, ref)
    worst = 0.0
    for i in eachindex(rs)
        b = M.IGRF(rs[i], θs[i], ϕs[i])
        for k in 1:3
            worst = max(worst, abs(b[k] - ref[i][k]) / ref[i][4])
        end
    end
    return worst
end

"黄金 DB 回归：|DB - DB_gold| / |DB_gold|"
function golden_err_DB(rs, θs, ϕs, ref)
    worst = 0.0
    for i in eachindex(rs)
        db = M.IGRF_dB(rs[i], θs[i], ϕs[i]).DB
        worst = max(worst, abs(db - ref[i]) / abs(ref[i]))
    end
    return worst
end

"""
    check_jacobian_fd(mod; n=30, seed=7) -> (err_r, err_θ, err_ϕ)

用四阶中心差分独立检验 IGRF_dB 的 9 个偏导（相对尺度：∂r 用 |B|/r，∂θ、∂ϕ 用 |B|）。
四阶公式 (8[f(x+h)-f(x-h)] - [f(x+2h)-f(x-2h)])/(12h) 的截断误差为 O(h^4)；
两点公式在低高度、高阶项显著时截断误差可达 1e-6 量级，不适合做断言。
"""
function check_jacobian_fd(mod; n=30, seed=7)
    rs, θs, ϕs = random_points(n; seed=seed, r_range=(3500.0, 5000.0), θ_range=(0.3, π - 0.3))
    hr, ha = 1e-2, 1e-5
    B3(r, θ, ϕ) = (b = mod.IGRF(r, θ, ϕ); (b[1], b[2], b[3]))
    d4(f, x, h) = (8 .* (f(x + h) .- f(x - h)) .- (f(x + 2h) .- f(x - 2h))) ./ (12h)
    er = eθ = eϕ = 0.0
    for i in 1:n
        r, θ, ϕ = rs[i], θs[i], ϕs[i]
        d = mod.IGRF_dB(r, θ, ϕ)
        fd_r = d4(x -> B3(x, θ, ϕ), r, hr)
        fd_θ = d4(x -> B3(r, x, ϕ), θ, ha)
        fd_ϕ = d4(x -> B3(r, θ, x), ϕ, ha)
        er = max(er, maximum(abs.(fd_r .- (d.DBRDRR, d.DBTDRR, d.DBPDRR))) / (d.BB / r))
        eθ = max(eθ, maximum(abs.(fd_θ .- (d.DBRDTH, d.DBTDTH, d.DBPDTH))) / d.BB)
        eϕ = max(eϕ, maximum(abs.(fd_ϕ .- (d.DBRDPH, d.DBTDPH, d.DBPDPH))) / d.BB)
    end
    return er, eθ, eϕ
end

"稳态零分配检查：预热一次后测量 f!(ws, ...) 的分配字节数。"
function alloc_of(f!, ws)
    f!(ws, 3600.0, 1.0, 2.0)
    return @allocated f!(ws, 3600.0, 1.0, 2.0)
end

function serial_loop!(f!, ws, out, rs, θs, ϕs)
    @inbounds for i in eachindex(rs)
        out[i] = f!(ws, rs[i], θs[i], ϕs[i])
    end
    return out
end

